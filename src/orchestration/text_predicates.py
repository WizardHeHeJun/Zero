"""确定性文本判据的可复用构件（纯正则、无 LLM、无状态、可单测）。

供 supervisor 的写入门判据（`_is_commitment` 等）组合使用；抽出为独立模块是议会二轮
张力 3 的明文要求——「未来指向」这类语用维度会被多个判据复用（承诺、日程、后续的
状态陈述类），各判据内联一份会重演 parse_importance 当初两处副本的老路。

判据设计须遵 `.claude/rules/text-predicate-admission.md`（蕴含论证 / 合取优先 /
预注册样本 / 已知漏报入册）。本模块函数是**维度谓词**（时态、句式），自身不是
完整判据——完整判据由消费方合取组装。
"""

from __future__ import annotations

import re

# 过去指向证据：显式过去时间词。命中即判非未来——回顾性叙述里即便出现未来词
# （「我上周三答应了她三点见」）也属叙述而非施行，故过去词优先级最高。
# 「之前」不在此表（2026-08-31 deadline 准入）：它是歧义词——「周五之前」是截止期限
# （未来），「我之前说过」是回顾副词（过去）——由 is_future_oriented 里
# 「deadline 形态 → 未来；残余裸『之前』 → 过去」的两段分流处理，不做单维一刀切。
_PAST_TIME_RE = re.compile(r"昨天|前天|上周|上个?月|刚才|刚刚|当时|已经")

# deadline 指称：「X之前 / X前」把参照时间锚在**未来事件或时点**上（Reichenbach 参照时间；
# 汉语后置方位词「前」的时间用法），语义 = 截止期限，未来相容。两支结构不同：
#
# 支 1「时点+之?前」（时点为**闭集词表**）：蕴含论证——「之前」是歧义词，前面是时点
#   （「周五之前」）才是截止期限；前面是主语（「我们之前」「老板之前」）是回顾副词
#   「previously」。主语是**开放类**（代词/复数/任意名词），排除表追不完——首轮
#   code-reviewer BLOCK 实测「咱们之前说好了」FP 证实——故按构造反转：**只认闭集时点**，
#   主语+之前 一律不命中（残余裸「之前」由消费方判回顾）。「之」可省，兼收「下周前」
#   「月底前」「三点前」。
# 支 2「X前」（无「之」，X 为开放类事件名）：「发版前」「下班前」类。三类反例按字符类排除：
#   时长单位（「三个月前」「五分钟前」= 过去指称，排除 天年月日时钟分秒周）·
#   空间/词化形态（「门前」「往前」「提前」「目前」「此前」，并以 (?!面|方|头) 拦
#   「前面/前方/前头」）。
#
# 已声明代价（样本册钉住）：① 事件名+**之**前（「发版之前」）与主语+之前同形，
# 随支 1 收窄被结构性放弃（宁漏勿误，KNOWN_MISSES）；② X 位恰为被排除字的真 deadline
# （「生日前」——「日前」的「近来」词化歧义所迫，KNOWN_MISSES）；③ 复合句含两处「之前」
# 时（「老板之前说好周五之前给答复」）后一处合法 deadline 会盖过前面的回顾标记 ⇒ 已知
# **误报**形态（复审 WARN·登记于样本册底部已知误报注释区，生产精确率复核时一并盯）。
_DEADLINE_RE = re.compile(
    r"(?:周[一二三四五六日天]|星期[一二三四五六日天]|明天|明晚|明早|后天|大后天|今天|今晚|"
    r"本周|这周|下周|这个?月|下个?月|月底|年底|周末|\d+\s*号|"
    r"[一二三四五六七八九十两零\d]+\s*点半?|\d+\s*[:：]\s*\d+)之?前"
    r"|(?:(?![之以往此面眼跟门目先从生胸台提当天年月日时钟分秒周])[一-鿿])前(?!面|方|头)"
)


def is_deadline_anchored(text: str) -> bool:
    """文本是否含「X前/X之前」的截止期限形态（X = 事件名/时点，见 _DEADLINE_RE 蕴含论证）。

    维度谓词：作 T 维（时间指称）与 F 维（未来相容）的一支，不单独当判据用。
    """
    return bool(text) and _DEADLINE_RE.search(text) is not None


# 未来指向证据：显式未来时间词（含相对词与星期指称）。星期/周末词单独出现不蕴含未来
# （「周三去的」），但配过去词会先被 _PAST_TIME_RE 拦截（「上周三」），且本谓词只是
# 合取的一维——误放行由消费方的其余维度（如 commissive）兜住。
_FUTURE_TIME_RE = re.compile(
    r"明天|明晚|明早|后天|大后天|今晚|待会儿?|等会儿?|回头|下周|下个?月|下次|"
    r"周末|以后|稍后|周[一二三四五六日天]|星期[一二三四五六日天]"
)

# 完成体近似：任意汉字后接「了」。粗但方向正确——438 轮实测的时态类误报
# （「晚上打了两把游戏」「省下来的时间全花在筛上了」）全部由此形态构成。
# 已知代价：动词后表完成的「了」与句末语气「了」不区分，会把少数现在时陈述判成过去；
# 但显式未来词优先于本检查（「约好了明天去」先命中「明天」⇒ 未来），损失有界。
_PERFECTIVE_RE = re.compile(r"[一-鿿]了")

# 疑问句式：句末问号 / 语气词收尾。问句是询问不是施行（「几点出发？」在问时间，
# 不在做承诺）——「叙述/询问 ≠ 施行」的语用排除，议会二轮张力 3 明文要求。
_QUESTION_RE = re.compile(r"[？?]\s*$|[吗呢]\s*[？?。]?\s*$")


def is_future_oriented(text: str) -> bool:
    """文本的时间指向是否与「未来」相容（弱谓词：主要价值在**排除过去时态**）。

    判定顺序（优先级递减；deadline 两级为 2026-08-31 准入新增）：
      1. 含显式过去时间词 → False（回顾性叙述，即便同句有未来词/截止语——
         「昨天答应了周五之前给他」是转述，样本册字面命中负例钉死此词序）。
      2. 含 deadline 形态「X前/X之前」→ True（「周五之前给他」「发版前交」把参照点锚在
         未来——须先于完成体检查，否则「答应了月底前交稿」的「了」会误杀真承诺）。
      3. 含残余裸「之前」（未成 deadline 形态：「我之前…」「之前说过…」）→ False
         （回顾副词——「之前」歧义的另一半，与第 2 级配对分流）。
      4. 含显式未来时间词 → True（「约好了明天去」的完成体「了」修饰的是约定动作，
         承诺内容仍指向未来——未来词优先于完成体检查，否则此类真承诺全灭）。
      5. 含完成体「V了」→ False（「晚上打了两把游戏」类时态误报的主拦截点）。
      6. 无任何时态证据 → True（未来**相容**而非未来**确证**——「下午三点见」无未来词
         也无过去词，若默认 False 则省略式约定全灭）。

    ⚠ 蕴含论证（准入标准第 1 条）：本谓词**单独不蕴含**任何目标概念——默认 True 的
    弱语义决定了它只能作合取的一维（排除过去），不得单独当判据用。
    """
    if not text:
        return False
    if _PAST_TIME_RE.search(text):
        return False
    if _DEADLINE_RE.search(text):
        return True
    if "之前" in text:
        return False
    if _FUTURE_TIME_RE.search(text):
        return True
    if _PERFECTIVE_RE.search(text):
        return False
    return True


def is_question(text: str) -> bool:
    """文本是否为疑问句式（句末 ？/? 或「吗/呢」收尾）。

    语用排除维：疑问是询问不是施行（asking ≠ committing）。只看句末不看句中——
    「你问我几点？三点见」这类复合句会被误伤，属已知有界代价（预注册样本未覆盖
    该形态；出现实测反例再收窄）。
    """
    return bool(text) and _QUESTION_RE.search(text) is not None
