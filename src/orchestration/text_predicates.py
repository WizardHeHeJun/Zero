"""确定性文本判据的可复用构件（纯正则、无 LLM、无状态、可单测）。

供 supervisor 的写入门判据（`_is_commitment` 等）组合使用；抽出为独立模块是议会二轮
张力 3 的明文要求——「未来指向」这类语用维度会被多个判据复用（承诺、日程、后续的
状态陈述类），各判据内联一份会重演 parse_importance 当初两处副本的老路。

判据设计须遵 `.claude/rules/text-predicate-admission.md`（蕴含论证 / 合取优先 /
预注册样本 / 已知漏报入册）。本模块函数是**维度谓词**（时态、句式），自身不是
完整判据——完整判据由消费方合取组装。
"""

from __future__ import annotations

import re

# 过去指向证据：显式过去时间词。命中即判非未来——回顾性叙述里即便出现未来词
# （「我上周三答应了她三点见」）也属叙述而非施行，故过去词优先级最高。
_PAST_TIME_RE = re.compile(r"昨天|前天|上周|上个?月|刚才|刚刚|之前|当时|已经")

# 未来指向证据：显式未来时间词（含相对词与星期指称）。星期/周末词单独出现不蕴含未来
# （「周三去的」），但配过去词会先被 _PAST_TIME_RE 拦截（「上周三」），且本谓词只是
# 合取的一维——误放行由消费方的其余维度（如 commissive）兜住。
_FUTURE_TIME_RE = re.compile(
    r"明天|明晚|明早|后天|大后天|今晚|待会儿?|等会儿?|回头|下周|下个?月|下次|"
    r"周末|以后|稍后|周[一二三四五六日天]|星期[一二三四五六日天]"
)

# 完成体近似：任意汉字后接「了」。粗但方向正确——438 轮实测的时态类误报
# （「晚上打了两把游戏」「省下来的时间全花在筛上了」）全部由此形态构成。
# 已知代价：动词后表完成的「了」与句末语气「了」不区分，会把少数现在时陈述判成过去；
# 但显式未来词优先于本检查（「约好了明天去」先命中「明天」⇒ 未来），损失有界。
_PERFECTIVE_RE = re.compile(r"[一-鿿]了")

# 疑问句式：句末问号 / 语气词收尾。问句是询问不是施行（「几点出发？」在问时间，
# 不在做承诺）——「叙述/询问 ≠ 施行」的语用排除，议会二轮张力 3 明文要求。
_QUESTION_RE = re.compile(r"[？?]\s*$|[吗呢]\s*[？?。]?\s*$")


def is_future_oriented(text: str) -> bool:
    """文本的时间指向是否与「未来」相容（弱谓词：主要价值在**排除过去时态**）。

    判定顺序（优先级递减）：
      1. 含显式过去时间词 → False（回顾性叙述，即便同句有未来词）。
      2. 含显式未来时间词 → True（「约好了明天去」的完成体「了」修饰的是约定动作，
         承诺内容仍指向未来——未来词优先于完成体检查，否则此类真承诺全灭）。
      3. 含完成体「V了」→ False（「晚上打了两把游戏」类时态误报的主拦截点）。
      4. 无任何时态证据 → True（未来**相容**而非未来**确证**——「下午三点见」无未来词
         也无过去词，若默认 False 则省略式约定全灭）。

    ⚠ 蕴含论证（准入标准第 1 条）：本谓词**单独不蕴含**任何目标概念——默认 True 的
    弱语义决定了它只能作合取的一维（排除过去），不得单独当判据用。
    """
    if not text:
        return False
    if _PAST_TIME_RE.search(text):
        return False
    if _FUTURE_TIME_RE.search(text):
        return True
    if _PERFECTIVE_RE.search(text):
        return False
    return True


def is_question(text: str) -> bool:
    """文本是否为疑问句式（句末 ？/? 或「吗/呢」收尾）。

    语用排除维：疑问是询问不是施行（asking ≠ committing）。只看句末不看句中——
    「你问我几点？三点见」这类复合句会被误伤，属已知有界代价（预注册样本未覆盖
    该形态；出现实测反例再收窄）。
    """
    return bool(text) and _QUESTION_RE.search(text) is not None
